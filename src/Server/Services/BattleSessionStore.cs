using System.Collections.Concurrent;
using System.Collections.Immutable;
using System.Diagnostics.CodeAnalysis;
using System.Threading;
using System.Threading.Tasks;
using RoguelikeCardGame.Core.Battle.State;
using RoguelikeCardGame.Core.Random;

namespace RoguelikeCardGame.Server.Services;

/// <summary>
/// 戦闘セッション 1 件分の状態 + RNG。
/// IRng は session 単位で再利用必須 (spec §4-1)。複数の PlayCard / EndTurn 呼出で
/// RNG state を継承し、Core の <c>BattleDeterminismTests</c> が要求する
/// 「単一 IRng を Start → PlayCard → EndTurn に貫通させる」契約を満たす。
/// </summary>
public sealed record BattleSession(BattleState State, IRng Rng)
{
    /// <summary>
    /// Immutable presentation history. Existing session construction remains source compatible,
    /// and commands opt in by replacing this property only after Core accepts the command.
    /// </summary>
    public BattleActionJournal ActionJournal { get; init; } = BattleActionJournal.Empty;

    /// <summary>
    /// Successful external command ids and their complete normalized payloads.
    /// This is separate from replay entry identity so user-controlled ids can
    /// never collide with CPU/resolution entries generated by the server.
    /// </summary>
    public ImmutableDictionary<string, BattleCommandReceipt> CommandReceipts { get; init; } =
        BattleCommandReceiptStore.Empty;
}

/// <summary>
/// 戦闘中の <see cref="BattleSession"/> を accountId 単位でメモリ保持する。
/// Phase 10.3-MVP 暫定: save に乗らない (リロードで戦闘進行リセット)。
/// Phase 10.5 で本格保存への移行を検討。
/// </summary>
public sealed class BattleSessionStore
{
    private readonly ConcurrentDictionary<string, BattleSession> _sessions =
        new(StringComparer.OrdinalIgnoreCase);
    // Gate は session 削除時にも残す。待機中 command が旧 gate を保持する間に
    // 同じ accountId 用の新 gate を作ると、2 本が同時実行され session が復活し得るため。
    // accountId は永続アカウント集合に属するので service lifetime 中の保持を許容する。
    private readonly ConcurrentDictionary<string, SemaphoreSlim> _commandLocks =
        new(StringComparer.OrdinalIgnoreCase);

    internal int CommandLockCount => _commandLocks.Count;

    /// <summary>
    /// 同一アカウントの戦闘 command を直列化する。
    /// BattleSession の State と可変 IRng は必ず同じ lease 内で読み書きすること。
    /// アカウントごとに別 semaphore を使うため、別アカウントの戦闘は並列に進行できる。
    /// </summary>
    public async ValueTask<IAsyncDisposable> AcquireCommandLockAsync(
        string accountId, CancellationToken cancellationToken)
    {
        var gate = _commandLocks.GetOrAdd(
            accountId, static _ => new SemaphoreSlim(initialCount: 1, maxCount: 1));
        await gate.WaitAsync(cancellationToken).ConfigureAwait(false);
        return new CommandLockLease(gate);
    }

    public bool TryGet(string accountId, [MaybeNullWhen(false)] out BattleSession session)
        => _sessions.TryGetValue(accountId, out session);

    public void Set(string accountId, BattleSession session)
        => _sessions[accountId] = session;

    public void Remove(string accountId)
        => _sessions.TryRemove(accountId, out _);

    /// <summary>
    /// 全 session を一括削除する。test 間の isolation 用。
    /// 本番経路では accountId 単位の <see cref="Remove"/> を使うこと。
    /// </summary>
    public void Clear() => _sessions.Clear();

    private sealed class CommandLockLease : IAsyncDisposable
    {
        private SemaphoreSlim? _gate;

        public CommandLockLease(SemaphoreSlim gate) => _gate = gate;

        public ValueTask DisposeAsync()
        {
            Interlocked.Exchange(ref _gate, null)?.Release();
            return ValueTask.CompletedTask;
        }
    }
}
